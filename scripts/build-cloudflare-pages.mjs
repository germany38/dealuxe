// Rebuilds .cloudflare-pages/, the folder Cloudflare Pages publishes for dealuxapp.com (see wrangler.toml).
//
// Cloudflare's free plan allows 20,000 files per deploy, and the site has more than that. So:
//  - Every section NOT listed in PROXIED is copied in as real files, and Cloudflare serves them itself.
//    (Real copies, not symlinks: Cloudflare's build doesn't follow symlinks, so they failed the deploy.)
//    Static files are free and unlimited, so they don't count toward the 100,000 requests/day limit.
//  - PROXIED sections are left out, and _routes.json sends them to functions/[[path]].js, which
//    fetches them from the Netlify site. Only these requests (plus /shop/<product> and
//    /tickets/<event> pages and Netlify API calls) count toward the daily limit.
//
// Cloudflare runs `node scripts/build-cloudflare-pages.mjs` as its build command on every push.
// The output folder is generated, so it is git-ignored and not committed.
// It fails if the deploy would exceed MAX_FILES. Netlify ignores the folder because its name starts with a dot.

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, '.cloudflare-pages');
// Set the Cloudflare build environment variable CF_PAGES_PLAN=paid after upgrading. The paid plan
// allows 100,000 files per deploy, so every section is published as static files: static requests
// are free and unlimited, and only /shop/<product>, /tickets/<event> and /.netlify/* still run Functions.
const PAID = String(process.env.CF_PAGES_PLAN || '').toLowerCase() === 'paid';
const MAX_FILES = PAID ? 99000 : 19900; // Plan limits are 100,000 / 20,000; keep headroom.

// Sections served through the forwarder instead of as Cloudflare files (free plan only).
// Chosen because they hold many files but get the least traffic per file.
const PROXIED = PAID ? [] : ['deals', 'jobs', 'videos', 'ads'];

// Never published on Cloudflare: private, build-only or tooling files.
const PRIVATE = new Set([
  'exclusive-files', 'netlify', 'db', 'scripts', 'edge-functions', 'functions', 'node_modules',
  'cloudflare-pages', 'netlify.toml', 'wrangler.toml', 'package.json', 'package-lock.json',
  'deno.lock', 'fetch-products.js', 'dealux_products (1).csv', '_routes.json',
]);

// Always forwarded: Netlify functions (login, coins, Stripe downloads, etc.) and images.
const ALWAYS_PROXIED = ['/.netlify/*'];

function countFiles(p) {
  const st = fs.statSync(p);
  if (!st.isDirectory()) return 1;
  let n = 0;
  for (const name of fs.readdirSync(p)) {
    if (name === '.DS_Store' || name === 'node_modules' || name === '.git') continue;
    n += countFiles(path.join(p, name));
  }
  return n;
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT);

let total = 0;
const copied = [];
for (const name of fs.readdirSync(ROOT).sort()) {
  if (name.startsWith('.') || PRIVATE.has(name) || PROXIED.includes(name)) continue;
  fs.cpSync(path.join(ROOT, name), path.join(OUT, name), {
    recursive: true,
    dereference: true,
    filter: (src) => !['.DS_Store', 'node_modules', '.git'].includes(path.basename(src)),
  });
  // _redirects/_headers are config, not counted as assets.
  if (name !== '_redirects' && name !== '_headers') total += countFiles(path.join(ROOT, name));
  copied.push(name);
}

const routes = {
  version: 1,
  description: 'Generated by scripts/build-cloudflare-pages.mjs',
  include: [
    ...ALWAYS_PROXIED,
    ...PROXIED.flatMap((d) => [`/${d}`, `/${d}/*`]),
    '/shop/*',
    '/tickets/*',
  ],
  exclude: ['/shop/', '/shop/brand/*', '/shop/department/*', '/shop/type/*', '/tickets/', '/tickets/show/*'],
};
fs.writeFileSync(path.join(OUT, '_routes.json'), JSON.stringify(routes, null, 2) + '\n');

console.log(`Copied ${copied.length} entries, ${total} files (limit ${MAX_FILES}).`);
console.log(`Plan: ${PAID ? 'paid' : 'free'}. Forwarded to Netlify: ${PROXIED.map((d) => `/${d}/`).join(', ') || 'none'}`);
if (total > MAX_FILES) {
  console.error(`Too many files for Cloudflare Pages (${PAID ? 'paid' : 'free'} plan). Add another section to PROXIED.`);
  process.exit(1);
}
